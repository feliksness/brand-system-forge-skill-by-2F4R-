function fmtEx(lang) {
  const n = (v, o) => { try { return new Intl.NumberFormat(lang, o).format(v); } catch (e) { return String(v); } };
  const d = o => { try { return new Intl.DateTimeFormat(lang, o).format(new Date(Date.UTC(2026, 10, 12))); } catch (e) { return '2026-11-12'; } };
  return `| \`${lang}\` | ${n(1450)} | ${n(1234567.5, { maximumFractionDigits: 1 })} | ${n(0.825, { style: 'percent', maximumFractionDigits: 1 })} | ${n(18400, { notation: 'compact', maximumFractionDigits: 1 })} | ${n(-3.2, { signDisplay: 'exceptZero', maximumFractionDigits: 1 })} | ${d({ day: 'numeric', month: 'short', year: 'numeric' })} |`;
}
