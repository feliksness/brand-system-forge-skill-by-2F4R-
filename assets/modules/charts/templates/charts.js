  function donutChart(type) {
    return make(type, function (ctx, o, W) {
      var d = pairs(o.data), tot = sum(d.map(function (x) { return x.value; })) || 1, pie = type === 'pie' || o.pie;
      var side = W >= 460, size = Math.min(side ? W * 0.46 : W, o.size || 300), H = side ? size : size + d.length * 26 + 12;
      var svg = svgFor(ctx, W, H, o, o.desc || d.map(function (x) { return x.label + ' ' + C.format(x.value / tot * 100, { lang: ctx.lang, unit: '%', decimals: 0 }); }).join(', ') + '.');
      ctx.legend.hidden = true;
      var g = el('g', null, svg), cx = size / 2, cy = size / 2, R = size / 2 - 4, th = pie ? R : Math.max(14, R * (CFG.base === 'round' || CFG.base === 'organic' ? 0.26 : 0.32)), r = R - th / 2;
      var a = -Math.PI / 2, gap = 2 / r, round = !pie && (CFG.cap === 'round'), pts = [];
      d.forEach(function (x, i) {
        var span = x.value / tot * Math.PI * 2, a0 = a + gap / 2, a1 = a + span - gap / 2, node;
        if (pie) node = el('path', { d: 'M' + cx + ' ' + cy + 'L' + rd(cx + R * Math.cos(a0)) + ' ' + rd(cy + R * Math.sin(a0)) + 'A' + R + ' ' + R + ' 0 ' + (a1 - a0 > Math.PI ? 1 : 0) + ' 1 ' + rd(cx + R * Math.cos(a1)) + ' ' + rd(cy + R * Math.sin(a1)) + 'Z', fill: fillFor(svg, i, o), class: P + '-c-slice', style: '--i:' + i }, g);
        else {
          var capA = round ? Math.min((th / 2) / r, (a1 - a0) / 2 - 0.001) : 0;
          node = el('path', { d: arc(cx, cy, r, a0 + capA, Math.max(a0 + capA + 0.001, a1 - capA)), fill: 'none', stroke: o.colors ? o.colors[i % o.colors.length] : (CFG.texture[i] ? hatch(svg, i) : cvar(i)), 'stroke-width': th, 'stroke-linecap': round ? 'round' : 'butt', class: P + '-c-arc', pathLength: 1, style: '--i:' + i }, g);
        }
        var mid = a + span / 2; pts.push({ x: cx + r * Math.cos(mid), y: cy + r * Math.sin(mid), nodes: [node], html: tipHTML(x.label, [['', ctx.fmt(x.value) + ' · ' + C.format(x.value / tot * 100, { lang: ctx.lang, unit: '%', decimals: 0 }), i]], false) });
        a += span;
      });
      if (!pie && o.center) {
        el('text', { x: cx, y: cy + 4, 'text-anchor': 'middle', class: P + '-c-big' }, g, o.center.value);
        if (o.center.label) el('text', { x: cx, y: cy + 26, 'text-anchor': 'middle', class: P + '-c-tick' }, g, o.center.label);
      }
      var lx = side ? size + 32 : 4, ly = side ? Math.max(18, cy - d.length * 28 / 2 + 10) : size + 24, lw = W - lx - 4;
      d.forEach(function (x, i) {
        var y = ly + i * 28; el('rect', { x: lx, y: y - 9, width: 12, height: 12, rx: CFG.corner === 'round' ? 6 : CFG.corner === 'soft' ? 3 : 0, fill: fillFor(svg, i, o) }, g);
        el('text', { x: lx + 22, y: y + 2, class: P + '-c-label' }, g, fitText(x.label, P + '-c-label', lw - 100));
        el('text', { x: W - 4, y: y + 2, 'text-anchor': 'end', class: P + '-c-value' }, g, C.format(x.value / tot * 100, { lang: ctx.lang, unit: '%', decimals: 0 }));
      });
      interact(ctx, svg, pts, W);
      tableFor(ctx, o, ['', o.unit || CFG.words.value || 'Value', '%'], d.map(function (x) { return [x.label, ctx.fmt(x.value), C.format(x.value / tot * 100, { lang: ctx.lang, unit: '%', decimals: 1 })]; }));
    });
  }
