// patterns.js — PATTERNS/SVG (seamless tiles) · PATTERNS/PNG (1600×1000 swatches) · PATTERNS/previews/tiling-check.png
const fs = require('fs'), path = require('path');

async function run(ctx) {
  const { b, F, gfx, cw } = ctx, U = ctx.CORE.util;
  const root = b.path('PATTERNS');
  ['SVG', 'PNG', 'previews'].forEach(d => fs.rmSync(path.join(root, d), { recursive: true, force: true }));
  const cws = Object.keys(cw), list = [];
  let files = 0;
  gfx.catalogue.forEach((p, i) => {
    const entry = Object.assign({}, p, { index: i + 1, files: {} });
    cws.forEach(k => {
      const svg = gfx.tileSVG(p.key, k), name = `${p.key}-${k}`;
      F.write(path.join(root, 'SVG', name + '.svg'), svg); files++;
      const P = gfx.pattern(p.key, k); entry.w = P.w; entry.h = P.h;
      entry.files[k] = { svg: `PATTERNS/SVG/${name}.svg`, png: `PATTERNS/PNG/${name}.png` };
      ctx.rasters.push({ svg: gfx.swatchSVG(p.key, k, 1600, 1000), out: path.join(root, 'PNG', name + '.png'), palette: !/halo|glow|mesh/.test(p.key) });
    });
    list.push(entry);
  });
  // seamless check: every tile drawn 3×3 as clipped copies (exactly how a renderer repeats it)
  const tiles = list.filter(p => p.tile), cols = 4, cell = 560, gap = 40, pad = 60, head = 90;
  const rows = Math.ceil(tiles.length / cols), W = pad * 2 + cols * cell + (cols - 1) * gap, H = head + pad + rows * (cell + 56) + (rows - 1) * gap;
  const ink = cw.paper.ink, sheet = [`<rect width="${W}" height="${H}" fill="#FFFFFF"/>`];
  tiles.forEach((p, i) => {
    const P = gfx.pattern(p.key, 'paper'), k = cell / (3 * Math.max(P.w, P.h)), x0 = pad + (i % cols) * (cell + gap), y0 = head + Math.floor(i / cols) * (cell + 56 + gap);
    let g = '';
    for (let a = 0; a < 3; a++) for (let c = 0; c < 3; c++) g += `<svg x="${a * P.w}" y="${c * P.h}" width="${P.w}" height="${P.h}" viewBox="0 0 ${P.w} ${P.h}"><rect width="${P.w}" height="${P.h}" fill="${cw.paper.bg}"/>${P.body}</svg>`;
    const ticks = [1, 2].map(t => `<path d="M${t * P.w} -14V0M${t * P.w} ${3 * P.h}v14M-14 ${t * P.h}H0M${3 * P.w} ${t * P.h}h14" stroke="${ink}" stroke-width="${1 / k}"/>`).join('');
    sheet.push(`<g transform="translate(${x0} ${y0}) scale(${k.toFixed(5)})"><rect width="${3 * P.w}" height="${3 * P.h}" fill="${cw.paper.bg}"/>${g}${ticks}</g>`);
  });
  ctx.tilingSheet = { W, H, body: sheet.join(''), tiles: tiles.map((p, i) => ({ key: p.key, title: p.title, x: pad + (i % cols) * (cell + gap), y: head + Math.floor(i / cols) * (cell + 56 + gap) + cell * Math.max(...[1]) })) };
  const labels = tiles.map((p, i) => { const P = gfx.pattern(p.key, 'paper'), k = cell / (3 * Math.max(P.w, P.h)); return { t: `${String(i + 1).padStart(2, '0')}  ${p.title} — tile ${P.w}×${P.h}`, x: pad + (i % cols) * (cell + gap), y: head + Math.floor(i / cols) * (cell + 56 + gap) + 3 * P.h * k + 30 }; });
  ctx.tilingLabels = labels;
  let txt = '';
  if (ctx.glyphs && ctx.glyphs.label) {
    const G = ctx.glyphs.label, m = ctx.glyphs.meta;
    txt += ctx.B.textSVG(G, `${b.name} · pattern tiles repeated 3×3 as clipped copies · ticks mark tile edges`, pad, 56, { size: 22, tracking: m.labelTracking, upper: m.labelUpper, fill: ink }).svg;
    labels.forEach(l => { txt += ctx.B.textSVG(G, l.t, l.x, l.y, { size: 18, tracking: m.labelTracking, upper: m.labelUpper, fill: ink }).svg; });
  }
  ctx.rasters.push({ svg: `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">${sheet.join('')}${txt}</svg>`, out: path.join(root, 'previews', 'tiling-check.png'), palette: false });
  ctx.patterns = list;
  ctx.counts.patterns = list.length; ctx.counts.patternFiles = files;
  F.write(b.path('SOURCE', 'JSON', 'patterns-graphics.json'), JSON.stringify({ note: 'Generated by the patterns-graphics module. Regenerate, do not edit.', colourways: cw, patterns: list.map(p => ({ key: p.key, title: p.title, family: p.family, tags: p.tags, derived: p.derived, tile: p.tile, size: [p.w, p.h], files: p.files })) }, null, 1));
}
module.exports = { run };
