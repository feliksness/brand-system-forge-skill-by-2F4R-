// generator.js — SOURCE/JS/<p>-graphics.js (engine + brand config for any page) and the file:// generator
// GRAPHICS/generator/{index.html, generator.css, generator.js, fonts-embed.js}.
const fs = require('fs'), path = require('path');
const SOCIAL = { 'instagram-post': ['Instagram post 4:5', 1080, 1350], 'instagram-square': ['Instagram square', 1080, 1080], 'instagram-story': ['Story 9:16', 1080, 1920], 'linkedin-post': ['LinkedIn post', 1200, 1200],
  'linkedin-banner': ['LinkedIn banner', 1584, 396], 'linkedin-carousel': ['LinkedIn carousel 4:5', 1080, 1350], 'facebook-post': ['Facebook post', 1200, 1200], 'facebook-cover': ['Facebook cover', 1640, 624], 'youtube-thumbnail': ['YouTube thumbnail', 1280, 720],
  'og-image': ['Link preview (OG)', 1200, 630], 'x-post': ['X post', 1600, 900], 'twitter-post': ['X post', 1600, 900], 'x-header': ['X header', 1500, 500], 'pinterest-pin': ['Pinterest pin', 1000, 1500], 'tiktok-cover': ['TikTok cover', 1080, 1920], 'event-cover': ['Event cover', 1920, 1005] };

function formats(b) {
  const out = [{ key: 'hero', label: 'Hero 1920×1080', w: 1920, h: 1080 }, { key: 'square', label: 'Square 1080×1080', w: 1080, h: 1080 }, { key: 'story', label: 'Story 1080×1920', w: 1080, h: 1920 }];
  (b.profile.social || []).forEach(k => { const s = SOCIAL[k]; if (s && !out.some(o => o.w === s[1] && o.h === s[2])) out.push({ key: k, label: `${s[0]} ${s[1]}×${s[2]}`, w: s[1], h: s[2] }); });
  if ((b.profile.print || []).some(p => /poster|flyer/.test(p))) out.push({ key: 'poster', label: 'Poster A-ratio 1240×1754', w: 1240, h: 1754 });
  return out;
}

function fontsEmbed(ctx) {
  const { b, B } = ctx; const files = B.fontFiles(b), tt = B.typeTokens(b);
  const fams = ['display', 'mono', 'sans'].map(r => B.familyOf(tt.fontVar[r] || b.stacks[r] || '')).filter((v, i, a) => v && a.indexOf(v) === i);
  const local = Object.keys(b.fonts).filter(k => k.indexOf('local-') === 0).map(k => b.fonts[k]);
  const items = []; let total = 0;
  fams.concat(local).forEach(fam => { const list = (files[fam] || []).filter(x => x.style === 'normal'); const pickF = list.filter(x => /-latin-(?!ext)/.test(path.basename(x.file))).concat(local.includes(fam) ? list : []).concat(list).filter((v, i, a) => a.indexOf(v) === i).slice(0, local.includes(fam) ? 2 : 1);
    pickF.forEach(x => { if (!fs.existsSync(x.file)) return; const buf = fs.readFileSync(x.file); if (total + buf.length > 900000) return; total += buf.length; items.push({ family: fam, style: 'normal', weight: '100 900', data: buf.toString('base64') }); }); });
  return { js: `/* ${b.name} — brand fonts (SIL OFL 1.1) embedded for SVG/PNG export from the generator. Generated; do not edit. */\nwindow.${b.G}_FONTS=${JSON.stringify(items)};\n`, n: items.length, kb: Math.round(total / 1024) };
}

function run(ctx) {
  const { b, F, gfx, cw } = ctx, T = path.join(__dirname, '..', 'templates');
  // ---- SOURCE/JS/<p>-graphics.js : engine + brand config, boots window.<G>.gfx
  const core = fs.readFileSync(path.join(__dirname, 'graphics-core.js'), 'utf8').replace(/\nif \(typeof module[^\n]*\n?$/, '\n');
  const cfg = { name: b.name, logoType: b.logoType, dna: b.dna, colourways: cw, formats: formats(b), eyebrow: b.brand.descriptor || (b.labels.posts || ''),
    monogram: gfx.unit && gfx.unit.kind === 'monogram' ? { kind: 'monogram', vb: gfx.unit.vb, parts: gfx.unit.parts.map(p => ({ d: p.d, tx: p.tx, ty: p.ty, c: p.c, l: p.l })), sil: gfx.unit.sil } : null };
  const js = `/* ==========================================================================
   ${b.name} — ${b.p}-graphics.js  (generated by the patterns-graphics module — regenerate, do not edit)
   The brand's graphic-language engine: seeded patterns, motifs and background compositions derived from
   the mark (mark-data.js) and the design DNA. Same code as the build, so pages reproduce the shipped tiles.
     <script src="…/SOURCE/JS/mark-data.js"></script>
     <script src="…/SOURCE/JS/${b.p}-graphics.js"></script>
     ${b.G}.gfx.catalogue                         → patterns of this brand
     ${b.G}.gfx.tileSVG('${gfx.catalogue[0].key}', 'paper')          → seamless SVG tile
     ${b.G}.gfx.swatchSVG(key, colourway, w, h, {seed, scale})
     ${b.G}.gfx.composition('foundation', 1920, 1080, {seed: 3}) → {body, safe}  (wrap body in an <svg>)
     ${b.G}.gfx.motif('${(b.dna.motifs || ['dot'])[0]}', {size: 400})
   Colourways: ${Object.keys(cw).join(' · ')}. Classic script, file:// safe.
   ========================================================================== */
(function (global) {
  'use strict';
${core}
  var CORE = GFXFactory(), CFG = ${JSON.stringify(cfg)};
  var units = CORE.fromMarkData(global.${b.G}_MARK, CFG.logoType, CFG.monogram);
  var NS = global.${b.G} = global.${b.G} || {};
  NS.gfxCore = CORE; NS.gfxConfig = CFG;
  NS.gfx = units.unit ? CORE.create({ name: CFG.name, dna: global.${b.G}_DNA || CFG.dna, unit: units.unit, mark: units.mark, colourways: CFG.colourways }) : null;
})(window);
`;
  F.write(b.path('SOURCE', 'JS', `${b.p}-graphics.js`), js);
  // ---- generator page
  const out = b.path('GRAPHICS', 'generator'); fs.rmSync(out, { recursive: true, force: true });
  const slug = b.name.toLowerCase().normalize('NFKD').replace(/[^\w]+/g, '-').replace(/^-|-$/g, '') || b.p;
  const rep = s => s.replace(/{{p}}/g, b.p).replace(/{{G}}/g, b.G).replace(/{{BRAND_NAME}}/g, esc(b.name)).replace(/{{BRAND_SLUG}}/g, slug).replace(/{{LANG}}/g, b.lang)
    .replace(/{{SAMPLE_NOTE}}/g, b.content._sample ? ' Headlines come from content.json — currently <strong>sample content</strong>.' : '');
  ['generator.html', 'generator.css', 'generator.js'].forEach(n => F.write(path.join(out, n === 'generator.html' ? 'index.html' : n), rep(fs.readFileSync(path.join(T, n), 'utf8'))));
  const fe = fontsEmbed(ctx); F.write(path.join(out, 'fonts-embed.js'), fe.js);
  ctx.generator = { fonts: fe.n, kb: fe.kb, formats: cfg.formats.length };
  ctx.shots.push({ in: path.join(out, 'index.html'), out: b.path('GRAPHICS', 'previews', 'generator.png'), w: 1600, h: 1000, wait: 600 });
}
function esc(s) { return String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])); }
module.exports = { run, formats };
