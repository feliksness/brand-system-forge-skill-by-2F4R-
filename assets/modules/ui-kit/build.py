def react_file(b, R):
    p, name = b.p, pascal(b.name)
    return f"""/* {b.name} — minimal React wrappers for {p}-ui.css (no build step needed by the kit; any JSX toolchain works).
   Load SOURCE/CSS/{p}-core.css + SOURCE/CSS/{p}-ui.css on the page. For behaviours (tabs, modals…) also load SOURCE/JS/{p}-ui.js
   and call window.{b.G}.ui.init(node) in an effect after rendering composite widgets. */
import React from 'react';

const cx = (...a) => a.filter(Boolean).join(' ');
const P = '{p}';

export function Button({{ variant = 'primary', size, icon, block, loading, as: Tag = 'button', className, children, ...rest }}) {{
  const props = Tag === 'button' ? {{ type: 'button', ...rest }} : rest;
  return (
    <Tag className={{cx(`${{P}}-btn`, `${{P}}-btn--${{variant}}`, size && `${{P}}-btn--${{size}}`, icon && `${{P}}-btn--icon`, block && `${{P}}-btn--block`, className)}}
      aria-busy={{loading || undefined}} {{...props}}>
      {{loading ? <span>{{children}}</span> : children}}
    </Tag>
  );
}}

export function Card({{ variant, title, href, meta, media, children, footer, className, ...rest }}) {{
  return (
    <article className={{cx(`${{P}}-card`, variant && `${{P}}-card--${{variant}}`, className)}} {{...rest}}>
      {{media && <div className={{`${{P}}-card__media`}}>{{media}}</div>}}
      <div className={{`${{P}}-card__body`}}>
        {{meta && <div className={{`${{P}}-card__meta`}}>{{meta}}</div>}}
        {{title && <h3 className={{`${{P}}-card__title`}}>{{href ? <a className={{`${{P}}-card__link`}} href={{href}}>{{title}}</a> : title}}</h3>}}
        {{children && <div className={{`${{P}}-card__text`}}>{{children}}</div>}}
      </div>
      {{footer && <div className={{`${{P}}-card__footer`}}>{{footer}}</div>}}
    </article>
  );
}}

export function Input({{ id, label, hint, error, required, as = 'input', className, ...rest }}) {{
  const auto = React.useId ? React.useId() : 'f';
  const fid = id || `${{P}}-${{auto}}`;
  const describedBy = [hint && `${{fid}}-hint`, error && `${{fid}}-msg`].filter(Boolean).join(' ') || undefined;
  const Control = as === 'textarea' ? 'textarea' : 'input';
  return (
    <div className={{cx(`${{P}}-field`, className)}}>
      <label className={{`${{P}}-field__label`}} htmlFor={{fid}}>{{label}}{{required && <span className={{`${{P}}-field__req`}}> Required</span>}}</label>
      {{hint && <p className={{`${{P}}-field__hint`}} id={{`${{fid}}-hint`}}>{{hint}}</p>}}
      <Control id={{fid}} className={{as === 'textarea' ? `${{P}}-textarea` : `${{P}}-input`}} required={{required}} aria-invalid={{error ? 'true' : undefined}} aria-describedby={{describedBy}} {{...rest}} />
      {{error && <p className={{`${{P}}-msg ${{P}}-msg--error`}} id={{`${{fid}}-msg`}}><span className="sr-only">Error: </span>{{error}}</p>}}
    </div>
  );
}}

export function Tag({{ variant, className, children, ...rest }}) {{
  return <span className={{cx(`${{P}}-tag`, variant && `${{P}}-tag--${{variant}}`, className)}} {{...rest}}>{{children}}</span>;
}}

export function Alert({{ tone = 'info', title, children, onDismiss, className, ...rest }}) {{
  return (
    <div className={{cx(`${{P}}-alert`, `${{P}}-alert--${{tone}}`, className)}} role={{tone === 'error' ? 'alert' : 'status'}} {{...rest}}>
      <span className={{`${{P}}-alert__icon`}} aria-hidden="true" data-{p}-icon={{{{ info: 'info', success: 'check', warning: 'warning', error: 'error' }}[tone]}} />
      <div className={{`${{P}}-alert__body`}}>
        {{title && <p className={{`${{P}}-alert__title`}}>{{title}}</p>}}
        {{children && <p className={{`${{P}}-alert__text`}}>{{children}}</p>}}
      </div>
      {{onDismiss && <button type="button" className={{`${{P}}-close`}} aria-label="Dismiss" onClick={{onDismiss}}>×</button>}}
    </div>
  );
}}

const {name}UI = {{ Button, Card, Input, Tag, Alert }};
export default {name}UI;
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--repo', required=True)
    ap.add_argument('--no-shots', action='store_true', help='skip PNG previews')
    ap.add_argument('--audit', action='store_true', help='render every theme and report rendered text contrast below AA (needs Playwright)')
    a = ap.parse_args()
    t0 = time.time()
    b = F.load(a.repo)
    p = b.p
    R = RC.build(b)
    ic = fallback_icons(R)

    files = {'css': b.path('SOURCE', 'CSS', f'{p}-ui.css'), 'js': b.path('SOURCE', 'JS', f'{p}-ui.js'),
             'json': b.path('SOURCE', 'JSON', 'ui-kit.json'), 'react': b.path('UI-DESIGN-SYSTEM', 'react', f'{pascal(b.name)}UI.jsx')}
    F.write(files['css'], build_css(b, R))
    F.write(files['js'], build_js(b, R, ic))

    at = 'UI-DESIGN-SYSTEM/components'
    comp_dir = b.path(at)
    os.makedirs(comp_dir, exist_ok=True)
    F.write(os.path.join(comp_dir, 'gallery.css'), sub(tpl('gallery.css'), {'p': p, 'BRAND_NAME': b.name}))
    g = Gallery(b, R, ic, at)
    body = g.build()
    head = (f'<link rel="stylesheet" href="{b.rel(at, f"SOURCE/CSS/{p}-ui.css")}"><link rel="stylesheet" href="gallery.css">'
            f'<meta name="description" content="{F.esc(b.name)} UI kit — components, states and themes">'
            '<script>(function(){try{if(/[?&]preview/.test(location.search))document.documentElement.classList.add("is-preview")}catch(e){}})()</script>')
    scripts = ('mark-data.js', 'wordmark-data.js', 'dna-data.js', 'content-data.js', '{p}-mark.js', '{p}-icons.js', '{p}-ui.js')
    html = F.page(b, 'UI kit', body, at, head=head, scripts=scripts)
    F.write(os.path.join(comp_dir, 'index.html'), html)
    rep = {'brand': b.name, 'generated_by': 'ui-kit', 'note': 'WCAG 2.x contrast of component colour choices per theme (text ≥ 4.5, non-text ≥ 3).',
           'themes': R['report']}
    F.write(os.path.join(comp_dir, 'contrast-report.json'), json.dumps(rep, indent=1, ensure_ascii=False))
    F.write(files['react'], react_file(b, R))
    inv = {'module': 'ui-kit', 'version': json.load(open(os.path.join(HERE, 'module.json')))['version'], 'prefix': p, 'global': b.G,
           'css': f'SOURCE/CSS/{p}-ui.css', 'js': f'SOURCE/JS/{p}-ui.js', 'gallery': f'{at}/index.html',
           'recipe': {k: R[k] for k in ('corner', 'angle', 'facets', 'density', 'motion', 'energy', 'case', 'shadow', 'crop', 'family')},
           'summary': RC.summary(R), 'components': {grp: [f'{p}-' + c.split(' ')[0] for c in items] for grp, items in COMPONENTS.items()},
           'behaviours': ['theme-switch', 'theme-toggle', 'header', 'menu-toggle', 'tabs', 'accordion', 'modal-open', 'tooltip', 'popover', 'dismiss', 'toast',
                          'validate', 'count', 'sort', 'file', 'range', 'search', 'copy'],
           'icons': 'SOURCE/JS/%s-icons.js' % p if os.path.exists(b.path('SOURCE', 'JS', f'{p}-icons.js')) else 'built-in fallback'}
    F.write(files['json'], json.dumps(inv, indent=1, ensure_ascii=False))

    shots = []
    if not a.no_shots:
        prev = os.path.join(comp_dir, 'previews')
        if os.path.isdir(prev):
            shutil.rmtree(prev)
        os.makedirs(prev, exist_ok=True)
        url = 'file://' + os.path.join(comp_dir, 'index.html')
        jobs = []
        for th in ('light', 'dark', 'contrast'):
            jobs.append({'in': f'{url}?preview&theme={th}', 'out': os.path.join(prev, f'overview-{th}.png'), 'w': 1440, 'h': 960, 'wait': 350})
        jobs.append({'in': f'{url}?preview&theme=light', 'out': os.path.join(prev, 'overview-mobile.png'), 'w': 390, 'h': 844, 'scale': 2, 'wait': 350})
        for sid in ('buttons', 'forms', 'cards', 'navigation', 'feedback', 'overlays', 'data', 'identity'):
            for th in ('light', 'dark'):
                jobs.append({'in': f'{url}?preview&theme={th}', 'out': os.path.join(prev, f'{sid}-{th}.png'), 'w': 1440, 'h': 1000, 'selector': f'#{sid}', 'wait': 300})
        F.shots(jobs)
        shots = [os.path.basename(j['out']) for j in jobs if os.path.exists(j['out'])]
        opt = os.path.join(HERE, '..', '..', '..', 'scripts', 'optimize_png.js')
        if shutil.which('node') and os.path.exists(opt):
            subprocess.run(['node', opt, prev], capture_output=True, timeout=300)
    write_readmes(b, R, g, files, shots)

    if a.audit:
        subprocess.run(['node', os.path.join(HERE, 'lib', 'audit.js'), os.path.join(comp_dir, 'index.html')], timeout=600)

    kb = os.path.getsize(files['css']) // 1024
    print(f"ui-kit: {p}-ui.css {kb} KB · {p}-ui.js · gallery {g.n_examples} examples · {len(shots)} previews · "
          f"{R['corner']}/{R['shadow']}/{R['motion']}/{R['density']} · {time.time() - t0:.0f}s")


if __name__ == '__main__':
    main()
