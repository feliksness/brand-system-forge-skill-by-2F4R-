#!/usr/bin/env python3
"""
ui-kit — token/DNA-driven UI component library for a brand repository.

usage:  python3 build.py --repo /abs/path/BRAND-REPO [--no-shots] [--audit]

Writes (all idempotent, owned by this module):
  SOURCE/CSS/<p>-ui.css                      components (recipe + core + shape layer + motion/motif flavour)
  SOURCE/JS/<p>-ui.js                        accessible behaviours (classic script, no deps)
  SOURCE/JSON/ui-kit.json                    recipe summary + component inventory (for website / brand-book modules)
  UI-DESIGN-SYSTEM/components/index.html     gallery + documentation (gallery.css next to it)
  UI-DESIGN-SYSTEM/components/previews/*.png overview + section crops, light / dark / contrast / mobile
  UI-DESIGN-SYSTEM/components/contrast-report.json
  UI-DESIGN-SYSTEM/react/<Brand>UI.jsx       minimal React wrappers (Button, Card, Input, Tag, Alert)
  UI-DESIGN-SYSTEM/README.md, components/README.md, tokens/README.md (if missing)
"""
