def sub(text, m):
    for k, v in m.items():
        text = text.replace('{{' + k + '}}', str(v))
    return text


def tpl(name):
    return open(os.path.join(TPL, name), encoding='utf-8').read()


def pascal(name):
    s = re.sub(r'[^0-9A-Za-z]+', ' ', name).title().replace(' ', '')
    return s if s and s[0].isalpha() else 'Brand' + s


def build_css(b, R):
    p = b.p
    plated = ', '.join(f'.{p}-{c}' for c in PLATED)
    tl = 'var(--_cut)' if R['facets'] else '0px'
    m = {'p': p, 'G': b.G, 'BRAND_NAME': b.name, 'PLATED': plated, 'ANGLE': f"{R['angle']:g}", 'TAN': f"{float(R['vars']['--ui-tan']):.3f}",
         'CORNERS': 'top-left + bottom-right (faceted)' if R['facets'] else 'bottom-right', 'TL': tl,
         'TAG_TL': 'var(--_k)' if R['facets'] else '0px', 'AV_TL': 'var(--_k)' if R['facets'] else '0px', 'CORNER': R['corner']}
    if R['corner'] == 'soft':
        ir = 'calc(var(--_r) - var(--ui-media-inset))'
        m['MEDIA_R'] = f'{ir} {ir} var(--radius-xl) {ir}' if R['family'] == 'organic' else ir
        m['MEDIA_R_H'] = f'{ir} {ir} {ir} var(--radius-xl)' if R['family'] == 'organic' else ir
    else:
        ir = 'calc(var(--_r) - var(--_bw))'
        m['MEDIA_R'] = f'{ir} {ir} 0 0'
        m['MEDIA_R_H'] = f'{ir} 0 0 {ir}'
    m['SEARCH_R'] = 'var(--radius-pill)' if R['corner'] == 'round' else 'var(--ui-r-control)'
    head = f"""/* ==========================================================================
   {b.name} — {p}-ui.css · UI component layer
   Generated by brand-system-forge / assets/modules/ui-kit from the design DNA:
     {RC.summary(R)}
   Load AFTER {p}-core.css (fonts + tokens + colours):
     <link rel="stylesheet" href="…/SOURCE/CSS/{p}-core.css">
     <link rel="stylesheet" href="…/SOURCE/CSS/{p}-ui.css">
     <script src="…/SOURCE/JS/{p}-icons.js"></script>  (optional)   <script src="…/SOURCE/JS/{p}-ui.js"></script>
   Gallery & docs: UI-DESIGN-SYSTEM/components/index.html
   Naming: .{p}-block · .{p}-block__element · .{p}-block--modifier · state in ARIA or .is-* ·
           .is-hover / .is-focus / .is-active are documentation snapshots only · --_x = private to a component.
   Every colour is a --color-* token; theme-dependent choices are re-declared per theme scope below.
   Regenerate: python3 build.py --repo <repo> (module folder) — hand edits are overwritten.
   ========================================================================== */
"""
    rec = '/* ---- RECIPE · theme-independent decisions (density, type voice, shape, motion) ---- */\n:root {\n' + RC.css_vars(R['vars']) + '\n}\n'
    rec += '@media (max-width: 767px) { :root { --ui-header-h: 64px; --ui-card-pad: var(--space-5); --ui-panel-pad: var(--space-6); } }\n'
    rec += '/* ---- RECIPE · per-theme colour choices (picked by measured WCAG contrast; see contrast-report.json) ---- */\n' + RC.theme_css(R)
    core = sub(tpl('ui-core.css'), m)
    shape = sub(tpl('shape-cut.css' if R['corner'] == 'cut' else 'shape-radius.css'), m)
    parts = [head, rec, core, shape, FL.motion(R, p), FL.family(R, p, b), FL.languages(R, p, b), FL.preferences(R, p, plated)]
    return '\n'.join(x for x in parts if x)


def build_js(b, R, ic):
    st = R['stroke']
    return sub(tpl('ui.js'), {'p': b.p, 'G': b.G, 'BRAND_NAME': b.name, 'ICONS_JSON': json.dumps(ic, ensure_ascii=False),
                              'ICON_ALIASES': json.dumps(ALIASES), 'STROKE_W': st.get('icon_px_at_24') or 1.75,
                              'STROKE_CAP': st.get('cap') or 'round', 'STROKE_JOIN': st.get('join') or 'round'})


def esc_md(s):
    return str(s).replace('<', '&lt;')


def shape_note(R):
    return {'cut': 'chamfers via a clip-path plate on `::before` (corners: ' + ('top-left + bottom-right' if R['facets'] else 'bottom-right') + '); hover wipes along the logo angle',
            'round': 'pill buttons, tags, chips and search; generous card radii; circular avatars and steps',
            'soft': 'large soft radii, inset media with an organic corner, no hard edges',
            'rounded': 'moderate radii from the radius tokens', 'square': 'crisp 0–2px corners'}[R['corner']]


def motion_note(R):
    return {'snap': 'short durations, no overshoot; press drops 1px, cards step onto a hard shadow',
            'slide': 'lateral moves of icons and indicators',
            'glide': 'smooth lift with growing depth; press settles with a slight scale',
            'flow': 'slow, springy toggles; surfaces float up a little'}[R['motion']]


