  function polyD(pts) { return 'M' + pts.map(function (q) { return q[0].toFixed(2) + ' ' + q[1].toFixed(2); }).join(' L') + 'Z'; }
  function apply(el, cache, k, v) { if (cache[k] === v) return; cache[k] = v; if (v === '' || v == null) el.removeAttribute(k); else el.setAttribute(k, v); }
  /** Transform string: translate(x,y) + rotate/scale about pivot (all in the element's own coords). */
  function tf(x, y, r, s, px, py) {
    var t = '';
    if (Math.abs(x) > 0.01 || Math.abs(y) > 0.01) t += 'translate(' + x.toFixed(2) + ' ' + y.toFixed(2) + ')';
    if (Math.abs(r) > 0.01 || Math.abs(s - 1) > 0.0005) t += ' translate(' + px.toFixed(2) + ' ' + py.toFixed(2) + ')' + (Math.abs(r) > 0.01 ? ' rotate(' + r.toFixed(2) + ')' : '') + (Math.abs(s - 1) > 0.0005 ? ' scale(' + s.toFixed(4) + ')' : '') + ' translate(' + (-px).toFixed(2) + ' ' + (-py).toFixed(2) + ')';
    return t.trim();
  }
  /**
   * Set a part's state. s: { x, y (root units), r (deg), s (scale), pivot [x,y] root (default: unit centre),
   *   o (opacity), fo (fill opacity), clip: [[x,y],…] polygon in root units | null, trace: 0…1 | null, traceO, traceColor }
   */
  Scene.prototype.set = function (p, s) {
    s = s || {};
    var mi = p.mi, x = s.x || 0, y = s.y || 0, piv = s.pivot || [p.unit ? p.unit.cx : p.cx, p.unit ? p.unit.cy : p.cy];
    var lx = mi.a * x + mi.c * y, ly = mi.b * x + mi.d * y, lp = [mi.a * piv[0] + mi.c * piv[1] + mi.e, mi.b * piv[0] + mi.d * piv[1] + mi.f];
    apply(p.el, p.cache, 'transform', tf(lx, ly, s.r || 0, s.s == null ? 1 : s.s, lp[0], lp[1]));
    if (p.under && p.under.getAttribute('display')) p.under.removeAttribute('display');
    var op = s.o == null ? 1 : s.o; apply(p.el, p.cache, 'opacity', op >= 0.999 ? '' : Math.max(0, op).toFixed(3));
    var fo = s.fo == null ? 1 : s.fo; apply(p.f, p.fcache, 'opacity', fo >= 0.999 ? '' : Math.max(0, fo).toFixed(3));
    if (s.clip) {
      var c = p.clip || (p.clip = this.clipEl('p' + p.idx));
      var loc = s.clip.map(function (q) { return [mi.a * q[0] + mi.c * q[1] + mi.e, mi.b * q[0] + mi.d * q[1] + mi.f]; });
      c.path.setAttribute('d', polyD(loc)); apply(p.el, p.cache, 'clip-path', 'url(#' + c.id + ')');
    } else apply(p.el, p.cache, 'clip-path', '');
    if (s.trace != null && s.trace > 0 && (s.traceO == null || s.traceO > 0)) {
      if (!p.tr) {
        p.tr = p.shape.cloneNode(false); p.tr.removeAttribute('id');
        p.tr.setAttribute('fill', 'none'); p.tr.setAttribute('pathLength', '1'); p.tr.setAttribute('stroke-dasharray', '1 1');
        p.tr.setAttribute('stroke-linejoin', CFG.join === 'miter' ? 'miter' : 'round'); p.tr.setAttribute('stroke-linecap', CFG.cap === 'square' ? 'square' : CFG.cap === 'butt' ? 'butt' : 'round');
        p.el.appendChild(p.tr); p.tcache = {};
      }
      var sw = (s.traceW || Math.max(this.box.w, this.box.h) * 0.0045) / p.sc;
      apply(p.tr, p.tcache, 'stroke', s.traceColor || 'currentColor');
      apply(p.tr, p.tcache, 'stroke-width', sw.toFixed(3));
      apply(p.tr, p.tcache, 'stroke-dashoffset', (1 - clamp01(s.trace)).toFixed(4));
      apply(p.tr, p.tcache, 'opacity', s.traceO == null || s.traceO >= 0.999 ? '' : s.traceO.toFixed(3));
      apply(p.tr, p.tcache, 'display', '');
    } else if (p.tr) apply(p.tr, p.tcache, 'display', 'none');
  };
