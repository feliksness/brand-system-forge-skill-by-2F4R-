  /** Player: plays any concept on a scene (rAF), honours reduced motion. */
  function Player(scene, concept, o) {
    this.scene = scene; this.concept = concept; this.o = o = assign({ speed: 1, loop: false, hold: 900 }, o);
    this.t = 0; this.playing = false; this.total = concept.total(scene); this.listeners = [];
  }
  Player.prototype.renderAt = function (t) {
    this.t = t;
    if (!this.concept.loop && t >= this.total) this.scene.finalize();
    else this.concept.render(this.scene, this.concept.loop ? t % this.total : Math.max(0, t));
    this.listeners.forEach(function (f) { f(t); });
  };
  Player.prototype.play = function (from) {
    var self = this; this.stop();
    if (from != null) this.t = from; if (this.t >= this.total && !this.concept.loop) this.t = 0;
    this.playing = true; var last = now();
    function step() {
      if (!self.playing) return;
      var n = now(), dt = (n - last) * self.o.speed; last = n;
      var t = self.t + dt;
      if (!self.concept.loop && t >= self.total) {
        self.renderAt(self.total);
        if (self.o.loop) { if (t >= self.total + self.o.hold) t = 0; else { self.t = t; self.id = raf(step); return; } }
        else { self.playing = false; if (self.o.onend) self.o.onend(); return; }
      }
      self.renderAt(t); self.id = raf(step);
    }
    this.id = raf(step);
  };
  Player.prototype.stop = function () { this.playing = false; if (this.id) caf(this.id); };
  Player.prototype.onTime = function (f) { this.listeners.push(f); };
