  var SHAPES = 'path,polygon,polyline,rect,circle,ellipse,line';
  function inDefs(n) { for (var p = n.parentNode; p && p.nodeType === 1; p = p.parentNode) if (/^(defs|mask|clipPath|pattern|symbol|linearGradient|radialGradient|marker)$/.test(p.localName)) return true; return false; }
  function bboxRoot(el, rootInv) {
    var b = el.getBBox(), m = rootInv.multiply(el.getCTM());
    var pts = [[b.x, b.y], [b.x + b.width, b.y], [b.x, b.y + b.height], [b.x + b.width, b.y + b.height]].map(function (q) { return [m.a * q[0] + m.c * q[1] + m.e, m.b * q[0] + m.d * q[1] + m.f]; });
    var xs = pts.map(function (q) { return q[0]; }), ys = pts.map(function (q) { return q[1]; });
    var x = Math.min.apply(null, xs), y = Math.min.apply(null, ys);
    return { x: x, y: y, w: Math.max.apply(null, xs) - x, h: Math.max.apply(null, ys) - y, m: m, lb: b };
  }
  function union(list) {
    var x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
    list.forEach(function (b) { if (!b || !b.w && !b.h) return; x0 = Math.min(x0, b.x); y0 = Math.min(y0, b.y); x1 = Math.max(x1, b.x + b.w); y1 = Math.max(y1, b.y + b.h); });
    return x0 === Infinity ? { x: 0, y: 0, w: 1, h: 1 } : { x: x0, y: y0, w: x1 - x0, h: y1 - y0 };
  }
  LM.union = union;
  /* split a compound typeset path into one path per glyph (contours clustered by x-overlap) */
  function splitCompound(shape) {
    if (shape.localName !== 'path') return [shape];
    var d = shape.getAttribute('d') || '';
    if (/m/.test(d) || (d.match(/M/g) || []).length < 2) return [shape];
    var subs = d.split(/(?=M)/).filter(function (s) { return s.trim(); });
    var tmp = subs.map(function (s) { var p = shape.cloneNode(false); p.setAttribute('d', s); shape.parentNode.insertBefore(p, shape); return { el: p, b: p.getBBox(), d: s }; });
    tmp.forEach(function (q) { q.el.remove(); });
    tmp.sort(function (a, b) { return a.b.x - b.b.x; });
    var groups = [];
    tmp.forEach(function (q) {
      var g = groups.find(function (G2) { var ov = Math.min(G2.x1, q.b.x + q.b.width) - Math.max(G2.x0, q.b.x); return ov > 0.45 * Math.min(q.b.width, G2.x1 - G2.x0); });
      if (g) { g.items.push(q); g.x0 = Math.min(g.x0, q.b.x); g.x1 = Math.max(g.x1, q.b.x + q.b.width); }
      else groups.push({ items: [q], x0: q.b.x, x1: q.b.x + q.b.width });
    });
    if (groups.length < 2) return [shape];
    var out = groups.map(function (g) { var p = shape.cloneNode(false); p.setAttribute('d', g.items.map(function (q) { return q.d; }).join(' ')); shape.parentNode.insertBefore(p, shape); return p; });
    shape.remove(); return out;
  }

  /**
   * new Scene(host, o)
   *   o.svg      logo SVG markup (required)        o.roles   { groupId: 'mark'|'lettering' } overrides
   *   o.aspect   frame w/h (16/9) · 0 = tight fit  o.fill    fraction of the frame the logo may occupy
   *   o.extras   [{ id, svg|node, at:'under'|'over', box:[x,y,w,h] (root units) | fitTo:'centre', final:'hide'|'keep' }]
   *   o.texts    [{ id, text, lang, size (root units), y (root units), family, weight, color, transform, tracking }]
   *   o.label    accessible name
   */
  function Scene(host, o) {
    this.o = o = assign({ aspect: 16 / 9, fill: 0.56, label: CFG.name + ' logo animation', roles: {} }, o);
    this.id = 'lm' + (++uid);
    var src = parseSVG(o.svg);
    var vb = (src.getAttribute('viewBox') || '0 0 100 100').split(/[\s,]+/).map(Number);
    host.innerHTML = '';
    var svg = this.svg = mk('svg', { class: P + '-lm-svg', role: 'img', 'aria-label': o.label, preserveAspectRatio: 'xMidYMid meet', viewBox: vb.join(' '), overflow: 'hidden' }, host);
    this.defs = mk('defs', null, svg);
    this.under = mk('g', { class: 'lm-under' }, svg);
    this.root = mk('g', { class: 'lm-root' }, svg);
    this.over = mk('g', { class: 'lm-over' }, svg);
    var self = this, kids = Array.prototype.slice.call(src.childNodes), loose = null;
    kids.forEach(function (n) {
      if (n.nodeType !== 1 || /^(title|desc|metadata|style)$/i.test(n.localName)) return;
      var c = doc.importNode(n, true);
      if (n.localName === 'g' || n.localName === 'defs') self.root.appendChild(c);
      else { if (!loose) loose = mk('g', { id: 'mark' }, self.root); loose.appendChild(c); }
    });
    // unique ids (several scenes per page) + fix references
    var map = {};
    $$('[id]', this.root).forEach(function (e) { var old = e.getAttribute('id'); if (!e.hasAttribute('data-lm-role')) e.setAttribute('data-lm-id', old); var nu = self.id + '-' + old; map[old] = nu; e.setAttribute('id', nu); });
    $$('*', this.root).forEach(function (e) {
      ['mask', 'clip-path', 'fill', 'stroke', 'filter', 'href', 'xlink:href'].forEach(function (a) {
        var v = e.getAttribute(a); if (!v) return;
        var nv = v.replace(/url\(#([^)]+)\)/g, function (_, k) { return 'url(#' + (map[k] || k) + ')'; }).replace(/^#(.+)$/, function (_, k) { return '#' + (map[k] || k); });
        if (nv !== v) e.setAttribute(a, nv);
      });
    });
    // groups → wrappers → parts
    this.groups = []; this.parts = [];
    var gi = 0;
    Array.prototype.slice.call(this.root.children).forEach(function (g) {
      if (g.localName !== 'g') return;
      var gid = g.getAttribute('data-lm-id') || ('g' + gi); gi++;
      var role = o.roles[gid] || (/letter|word|name|type/i.test(gid) ? 'lettering' : 'mark');
      var gw = mk('g', { class: 'lm-g', 'data-group': gid });
      g.parentNode.insertBefore(gw, g); gw.appendChild(g);
      var grp = { id: gid, role: role, el: gw, inner: g, parts: [] };
      var shapes = $$(SHAPES, g).filter(function (s) { return !inDefs(s); });
      if (role === 'lettering') { var more = []; shapes.forEach(function (s) { more = more.concat(splitCompound(s)); }); shapes = more; }
      shapes.forEach(function (s) {
        var pw = mk('g', { class: 'lm-p' }), pf = mk('g', { class: 'lm-f' });
        s.parentNode.insertBefore(pw, s); pw.appendChild(pf); pf.appendChild(s);
        var fill = hexOf(s.getAttribute('fill')) || hexOf(global.getComputedStyle(s).fill) || hexOf(s.getAttribute('stroke'));
        var stroked = (s.getAttribute('fill') === 'none' || global.getComputedStyle(s).fill === 'none') && !!s.getAttribute('stroke');
        var part = { el: pw, f: pf, shape: s, group: grp, fill: fill, lum: lumOf(fill), stroked: stroked, idx: self.parts.length, cache: {}, fcache: {} };
        grp.parts.push(part); self.parts.push(part);
      });
      self.groups.push(grp);
    });
    this.measure();
    this.extras = {}; this.texts = {};
    (o.extras || []).forEach(function (x) { self.addExtra(x); });
    (o.texts || []).forEach(function (x) { self.addText(x); });
    this.fit();
  }
  LM.Scene = Scene;
  Scene.prototype.measure = function () {
    var inv = this.root.getCTM().inverse(), self = this;
    this.parts.forEach(function (p) {
      var b = bboxRoot(p.el, inv); p.rb = b; p.m = b.m; p.mi = b.m.inverse();
      p.cx = b.x + b.w / 2; p.cy = b.y + b.h / 2; p.area = Math.max(1, b.w * b.h);
      p.sc = Math.sqrt(Math.abs(b.m.a * b.m.d - b.m.b * b.m.c)) || 1;
    });
    this.groups.forEach(function (g) { g.rb = union(g.parts.map(function (p) { return p.rb; })); g.cx = g.rb.x + g.rb.w / 2; g.cy = g.rb.y + g.rb.h / 2; });
    this.box = union(this.groups.map(function (g) { return g.rb; }));
    this.cluster();
  };
  /** Units = what animates together: glyphs (lettering) or parts with their counters (marks). Frames detected for emblems. */
  Scene.prototype.cluster = function () {
    var self = this;
    this.units = [];
    this.groups.forEach(function (g) {
      var units = [];
      if (g.role === 'lettering') {
        var list = g.parts.slice().sort(function (a, b) { return a.rb.x - b.rb.x; });
        list.forEach(function (p) {
          var u = units.find(function (u2) {
            var ov = Math.min(u2.x1, p.rb.x + p.rb.w) - Math.max(u2.x0, p.rb.x), narrow = Math.min(p.rb.w, u2.x1 - u2.x0);
            var gap = Math.max(u2.y0, p.rb.y) - Math.min(u2.y1, p.rb.y + p.rb.h), tall = Math.max(u2.y1 - u2.y0, p.rb.h);
            return ov > 0.5 * narrow && gap < 0.5 * tall;
          });
          if (u) { u.parts.push(p); u.x0 = Math.min(u.x0, p.rb.x); u.x1 = Math.max(u.x1, p.rb.x + p.rb.w); u.y0 = Math.min(u.y0, p.rb.y); u.y1 = Math.max(u.y1, p.rb.y + p.rb.h); }
          else units.push({ parts: [p], x0: p.rb.x, x1: p.rb.x + p.rb.w, y0: p.rb.y, y1: p.rb.y + p.rb.h });
        });
      } else {
        var garea = g.rb.w * g.rb.h;
        g.parts.forEach(function (p) { p.frame = g.parts.length > 3 && p.area > 0.5 * garea; });
        g.parts.forEach(function (p, i) {
          var parent = null;
          if (!p.frame && p.area < 0.25 * garea) {
            // counters / inlays: a smaller part fully inside a bigger, differently filled part whose ink surrounds it
            for (var j = i - 1; j >= 0; j--) {
              var q = g.parts[j]; if (q.frame || q.area <= p.area * 2 || q.fill === p.fill) continue;
              if (p.rb.x < q.rb.x - 1 || p.rb.y < q.rb.y - 1 || p.rb.x + p.rb.w > q.rb.x + q.rb.w + 1 || p.rb.y + p.rb.h > q.rb.y + q.rb.h + 1) continue;
              try {
                var mi = self.root.getCTM().inverse().multiply(q.shape.getCTM()).inverse(), hit = 0, ex = p.rb.w * 0.12 + 0.5, ey = p.rb.h * 0.12 + 0.5;
                [[p.rb.x - ex, p.rb.y - ey], [p.cx, p.rb.y - ey], [p.rb.x + p.rb.w + ex, p.rb.y - ey], [p.rb.x + p.rb.w + ex, p.cy], [p.rb.x + p.rb.w + ex, p.rb.y + p.rb.h + ey], [p.cx, p.rb.y + p.rb.h + ey], [p.rb.x - ex, p.rb.y + p.rb.h + ey], [p.rb.x - ex, p.cy]].forEach(function (pt) {
                  if (q.shape.isPointInFill(new DOMPoint(mi.a * pt[0] + mi.c * pt[1] + mi.e, mi.b * pt[0] + mi.d * pt[1] + mi.f))) hit++;
                });
                if (hit >= 5) { parent = q; break; }
              } catch (e) { /* engines without isPointInFill: no counters */ }
            }
          }
          if (parent && parent.unit) { parent.unit.parts.push(p); p.unit = parent.unit; }
          else { var u = { parts: [p], frame: p.frame }; p.unit = u; units.push(u); }
        });
      }
      units.forEach(function (u, k) {
        u.group = g; u.role = g.role; u.k = k;
        u.rb = union(u.parts.map(function (p) { return p.rb; }));
        u.cx = u.rb.x + u.rb.w / 2; u.cy = u.rb.y + u.rb.h / 2; u.area = u.rb.w * u.rb.h;
        u.lum = u.parts[0].lum; u.fill = u.parts[0].fill;
        u.parts.forEach(function (p) { p.unit = u; });
      });
      g.units = units; self.units = self.units.concat(units);
      // a frame with holes (e.g. lettering knocked out of a badge) gets a solid underlay while the content is still arriving
      if (units.some(function (u) { return !u.frame; })) units.forEach(function (u) { if (u.frame) u.parts.forEach(function (p) { self.underlay(p); }); });
    });
  };
