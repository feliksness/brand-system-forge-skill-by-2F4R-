  /* ---- geometry helpers for wipes (root coordinates) */
  var CUT = (CFG.angle || 60) * Math.PI / 180;
  var AX = { n: [Math.sin(CUT), Math.cos(CUT)], d: [Math.cos(CUT), -Math.sin(CUT)] };   // n = front normal (→↘), d = edge direction (↗)
  LM.axis = AX;
  function proj(x, y) { return x * AX.n[0] + y * AX.n[1]; }
  function boxProj(b) { var ps = [[b.x, b.y], [b.x + b.w, b.y], [b.x, b.y + b.h], [b.x + b.w, b.y + b.h]].map(function (q) { return proj(q[0], q[1]); }); return [Math.min.apply(null, ps), Math.max.apply(null, ps)]; }
  /** Half-plane {proj ≤ k} as a big quad around box b. reverse → {proj ≥ k}. */
  function angledClip(b, p, reverse) {
    var r = boxProj(b), k = lerp(r[0] - 1, r[1] + 1, p), cx = b.x + b.w / 2, cy = b.y + b.h / 2, L = (b.w + b.h) * 2;
    var base = [cx + AX.n[0] * (k - proj(cx, cy)), cy + AX.n[1] * (k - proj(cx, cy))], sgn = reverse ? 1 : -1;
    return [[base[0] + AX.d[0] * L, base[1] + AX.d[1] * L], [base[0] - AX.d[0] * L, base[1] - AX.d[1] * L],
            [base[0] - AX.d[0] * L + sgn * AX.n[0] * L, base[1] - AX.d[1] * L + sgn * AX.n[1] * L], [base[0] + AX.d[0] * L + sgn * AX.n[0] * L, base[1] + AX.d[1] * L + sgn * AX.n[1] * L]];
  }
  function rectClip(b, p, dir) {   // dir: 'up' (rise from bottom) | 'right'
    var pad = Math.max(b.w, b.h) * 0.04;
    if (dir === 'right') { var x = b.x - pad + (b.w + 2 * pad) * p; return [[b.x - pad, b.y - pad], [x, b.y - pad], [x, b.y + b.h + pad], [b.x - pad, b.y + b.h + pad]]; }
    var y = b.y + b.h + pad - (b.h + 2 * pad) * p; return [[b.x - pad, y], [b.x + b.w + pad, y], [b.x + b.w + pad, b.y + b.h + pad], [b.x - pad, b.y + b.h + pad]];
  }
  function circleClip(cx, cy, r, n) { var pts = []; n = n || 72; for (var i = 0; i < n; i++) { var a = i / n * Math.PI * 2; pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]); } return pts; }
  function wedgeClip(cx, cy, r, a0, sweep) {
    var pts = [[cx, cy]], n = Math.max(2, Math.ceil(sweep / 5));
    for (var i = 0; i <= n; i++) { var a = (a0 + sweep * i / n) * Math.PI / 180; pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]); }
    return pts;
  }
  LM.clips = { angled: angledClip, rect: rectClip, circle: circleClip, wedge: wedgeClip };

  /* ---- ordering */
  function order(units, how, S) {
    var b = S.markBox(), cx = b.x + b.w / 2, cy = b.y + b.h / 2, list = units.slice();
    var key = {
      lum: function (u) { return u.lum; }, 'lum-desc': function (u) { return -u.lum; },
      axis: function (u) { return proj(u.cx, u.cy); }, radial: function (u) { return Math.hypot(u.cx - cx, u.cy - cy); },
      x: function (u) { return u.cx; }, up: function (u) { return -u.cy; }, area: function (u) { return -u.area; }, doc: function (u) { return u.parts[0].idx; },
      centre: function (u) { return Math.abs(u.cx - cx); },
      angle: function (u) { return (Math.atan2(u.cy - cy, u.cx - cx) + Math.PI * 2.5) % (Math.PI * 2); }
    }[how] || function (u) { return u.parts[0].idx; };
    list.sort(function (a, c) { return key(a) - key(c); });
    var lo = key(list[0] || {}), hi = key(list[list.length - 1] || {});
    list.forEach(function (u, i) { u.rank = list.length > 1 ? i / (list.length - 1) : 0; u.rankV = hi !== lo ? (key(u) - lo) / (hi - lo) : u.rank; });
    return list;
  }
  LM.order = order;

  /* ---- verbs: one unit, eased progress → state. Character decides the vocabulary. */
  var V = LM.verbs = {};
  /** Assemble: units arrive from an exploded state. */
  V.assemble = function (S, u, t, a, d, o) {
    var raw = seg(t, a, a + d), b = S.markBox(), cx = b.x + b.w / 2, cy = b.y + b.h / 2, W = Math.max(b.w, b.h);
    var spread = W * (0.10 + 0.32 * E) * (o.spread || 1), dx = u.cx - cx, dy = u.cy - cy, r = Math.hypot(dx, dy) || 1, nx = dx / r, ny = dy / r, rn = Math.min(1, r / (W * 0.5));
    if (raw >= 1) return S.setUnit(u, {});
    var st;
    if (CH === 'snap') {
      var e = EASE.enter(raw), k = 1 - e, dn = nx * AX.n[0] + ny * AX.n[1], dd = nx * AX.d[0] + ny * AX.d[1], ax = Math.abs(dn) > Math.abs(dd) ? AX.n : AX.d, sg = (Math.abs(dn) > Math.abs(dd) ? dn : dd) < 0 ? -1 : 1;
      var dist = spread * (0.35 + 0.65 * rn);
      st = { x: ax[0] * sg * dist * k, y: ax[1] * sg * dist * k, o: Math.min(1, raw * 4) };
    } else if (CH === 'slide') {
      var e2 = EASE.enter(raw), step = W / 8, side = dx < 0 ? -1 : 1, rows = Math.round(dist2(u, b) * 4) || 1;
      st = { x: side * step * rows * (1 - e2), o: Math.min(1, raw * 3) };
    } else if (CH === 'glide') {
      var e3 = EASE.enter(raw), k3 = 1 - e3;
      st = { r: -(28 + 40 * E) * k3, s: 1 - 0.35 * k3, pivot: [cx, cy], o: Math.min(1, raw * 2.2) };
    } else {
      var e4 = EASE.emphasis(raw), k4 = 1 - e4;
      st = { x: nx * spread * 0.35 * k4, y: spread * 0.55 * k4 + ny * spread * 0.2 * k4, s: 1 - 0.06 * (1 - EASE.enter(raw)), o: EASE.standard(Math.min(1, raw * 1.6)) };
    }
    S.setUnit(u, st);
  };
  function dist2(u, b) { return Math.abs(u.cx - (b.x + b.w / 2)) / (b.w / 2 || 1); }
  /** Build: the unit itself is revealed (wipe / rise / sweep / soft drift). */
  V.build = function (S, u, t, a, d, o) {
    var raw = seg(t, a, a + d); o = o || {};
    if (raw >= 1) return S.setUnit(u, {});
    if (raw <= 0) return S.setUnit(u, { o: 0 });
    var b = u.rb, st;
    if (CH === 'snap') {
      var e = EASE.enter(raw), sh = Math.max(b.w, b.h) * 0.06 * (1 - e);
      st = { clip: angledClip(b, e, o.reverse), x: AX.n[0] * -sh, y: AX.n[1] * -sh };
    } else if (CH === 'slide') {
      var e2 = EASE.enter(raw);
      st = { clip: rectClip(b, e2, o.dir || 'up'), y: (o.dir === 'right' ? 0 : b.h * 0.18 * (1 - e2)), x: (o.dir === 'right' ? -b.w * 0.12 * (1 - e2) : 0) };
    } else if (CH === 'glide') {
      var e3 = EASE.enter(raw), ring = Math.abs(b.w - b.h) < 0.15 * Math.max(b.w, b.h) && u.area > 0.25 * S.markBox().w * S.markBox().h;
      if (ring) st = { clip: wedgeClip(u.cx, u.cy, Math.max(b.w, b.h), -90, 360 * e3), s: 0.92 + 0.08 * e3 };
      else st = { s: 0.3 + 0.7 * EASE.emphasis(raw), o: Math.min(1, raw * 2.5) };
    } else {
      var e4 = EASE.emphasis(raw);
      st = { y: b.h * 0.22 * (1 - e4), s: 0.97 + 0.03 * e4, o: EASE.standard(Math.min(1, raw * 1.4)) };
    }
    S.setUnit(u, st);
  };
  /** Pop: quick scale-in at the unit's own centre (light-sweep concept). */
  V.pop = function (S, u, t, a, d) {
    var raw = seg(t, a, a + d);
    if (raw >= 1) return S.setUnit(u, {});
    var e = (CH === 'snap' || CH === 'slide' ? EASE.enter : EASE.emphasis)(raw);
    S.setUnit(u, { s: 0.35 + 0.65 * e, o: Math.min(1, raw * 3) });
  };

  /* ---- lettering: group wipe or per-glyph stagger, by character */
  LM.letters = function (S, t, a, dur, o) {
    o = o || {};
    var groups = S.groups.filter(function (g) { return g.role === 'lettering'; });
    groups.forEach(function (g) {
      var raw = seg(t, a, a + dur);
      var mode = o.mode || (CH === 'snap' ? 'wipe' : 'stagger');
      if (raw >= 1) { S.setGroup(g, {}); g.units.forEach(function (u) { S.setUnit(u, {}); }); return; }
      if (mode === 'wipe' || CH === 'snap' && mode !== 'stagger') {
        g.units.forEach(function (u) { S.setUnit(u, {}); });
        var e = EASE.enter(raw), H = g.rb.h, sh = H * 0.25 * (1 - e);
        if (CH === 'flow') S.setGroup(g, { soft: { p: EASE.standard(raw), angle: 0, feather: 0.35 }, x: -sh * 0.6 });
        else if (CH === 'glide') S.setGroup(g, { clip: circleClip(g.cx, g.cy, Math.hypot(g.rb.w, g.rb.h) / 2 * e), s: 0.96 + 0.04 * e });
        else if (CH === 'slide') S.setGroup(g, { clip: rectClip(g.rb, e, 'right'), x: -sh });
        else S.setGroup(g, { clip: angledClip(g.rb, e), x: -sh });
        return;
      }
      // per-glyph stagger
      S.setGroup(g, CH === 'slide' ? { clip: rectClip({ x: g.rb.x - g.rb.w, y: g.rb.y - g.rb.h, w: g.rb.w * 3, h: g.rb.h * 2 }, 1) } : {});
      var units = order(g.units, CH === 'glide' ? 'centre' : 'x', S), n = units.length, each = Math.min(dur * 0.62, Math.max(dur * 0.35, DUR.slower)), spread = Math.max(0, dur - each);
      units.forEach(function (u) {
        var s0 = a + u.rank * spread, r = seg(t, s0, s0 + each), H = g.rb.h;
        if (r >= 1) return S.setUnit(u, {});
        if (r <= 0) return S.setUnit(u, { o: 0 });
        var st;
        if (CH === 'slide') { var e = EASE.enter(r); st = { y: (u.rb.y + u.rb.h - g.rb.y) * (1 - e) * 1.02 + 1, clip: [[u.rb.x - H, g.rb.y - H * 0.6], [u.rb.x + u.rb.w + H, g.rb.y - H * 0.6], [u.rb.x + u.rb.w + H, g.rb.y + g.rb.h + 1], [u.rb.x - H, g.rb.y + g.rb.h + 1]] }; }
        else if (CH === 'glide') { var e3 = EASE.enter(r); st = { s: 0.6 + 0.4 * e3, o: Math.min(1, r * 2.2), pivot: [u.cx, u.rb.y + u.rb.h] }; }
        else if (CH === 'snap') { var e1 = EASE.enter(r); st = { clip: angledClip(u.rb, e1), x: -H * 0.08 * (1 - e1) }; }
        else { var e4 = EASE.emphasis(r); st = { y: H * 0.35 * (1 - e4), o: EASE.standard(Math.min(1, r * 1.5)) }; }
        if (st.clip && CH === 'slide') {
          // slide: glyph rises from the baseline inside a fixed window → clip must not move with the glyph
          var yoff = st.y || 0; st.clip = st.clip.map(function (q) { return [q[0], q[1] - yoff]; });
        }
        S.setUnit(u, st);
      });
    });
  };

