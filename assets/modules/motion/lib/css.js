// Generates SOURCE/CSS/<p>-motion.css from the design DNA. Every value is a token or derived from the DNA.
'use strict';
module.exports = function motionCSS(b, M) {
  const p = b.p, ch = M.character, E = M.energy;
  const travel = Math.round(8 + 24 * E), stagger = Math.round(40 + 70 * E);
  const wipeDeg = 180 - M.angle;                    // CSS gradient angle whose iso-lines run at the cut angle
  const cropDeg = 180 - (M.crop || M.angle);
  const revealEase = ch === 'flow' ? 'var(--ease-emphasis)' : 'var(--ease-enter)';
  const autoKind = { snap: 'wipe', slide: 'rise', glide: 'scale', flow: 'drift' }[ch] || 'rise';
  const pressMove = ch === 'glide' || ch === 'flow' ? 'scale(.97)' : 'translateY(1px)';
  const zoom = { snap: 1.03, slide: 1.03, glide: 1.05, flow: 1.04 }[ch] || 1.04;
  const shadowHover = /hard/.test(M.shadow) ? 'var(--shadow-2)' : 'var(--shadow-3)';
  const sel = (kind, extra = '') => `.${p}-motion [data-reveal="${kind}"]:not([data-reveal-stagger])${extra}, .${p}-motion [data-reveal="${kind}"][data-reveal-stagger] > *${extra}`;
  const hid = kind => `.${p}-motion [data-reveal="${kind}"]:not([data-reveal-stagger]):not(.is-revealed), .${p}-motion [data-reveal="${kind}"][data-reveal-stagger]:not(.is-revealed) > *`;
  const delay = `calc(var(--${p}-delay, 0ms) + var(--${p}-i, 0) * var(--${p}-stagger))`;
  const maskLin = deg => `linear-gradient(${deg}deg, #000 calc(var(--${p}-p) * 100%), transparent calc(var(--${p}-p) * 100% + 1px))`;
  const maskSoft = deg => `linear-gradient(${deg}deg, #000 calc(var(--${p}-p) * 130% - 30%), transparent calc(var(--${p}-p) * 130%))`;
  const maskByCrop = {
    angled: maskLin(cropDeg), rect: maskLin(0), rounded: `radial-gradient(farthest-corner at 50% 100%, #000 calc(var(--${p}-p) * 100%), transparent calc(var(--${p}-p) * 100% + 1px))`,
    circle: `radial-gradient(circle at 50% 50%, #000 calc(var(--${p}-p) * 75%), transparent calc(var(--${p}-p) * 75% + 1px))`,
    organic: `radial-gradient(ellipse 70% 80% at 40% 60%, #000 calc(var(--${p}-p) * 140% - 25%), transparent calc(var(--${p}-p) * 140%))`
  };
  const mediaMask = maskByCrop[M.imagery] || maskByCrop.rect;
  const wipeMask = ch === 'slide' ? maskLin(90) : ch === 'flow' ? maskSoft(wipeDeg) : maskLin(wipeDeg);
  const sweep = {
    snap: `transform: translateX(-104%) skewX(${-(90 - M.angle)}deg); transform-origin: 0 100%;`,
    slide: `transform: translateY(101%);`,
    glide: `transform: translate(-50%, -50%) scale(0); left: 50%; top: 50%; right: auto; bottom: auto; width: 220%; aspect-ratio: 1; height: auto; border-radius: 50%;`,
    flow: `transform: translateY(70%); opacity: 0; background: linear-gradient(0deg, var(--${p}-sweep-color) 55%, transparent);`
  }[ch];
  const sweepOn = {
    snap: `transform: translateX(0) skewX(${-(90 - M.angle)}deg);`, slide: `transform: translateY(0);`,
    glide: `transform: translate(-50%, -50%) scale(1);`, flow: `transform: translateY(0); opacity: 1;`
  }[ch];
  const shimmerBg = {
    snap: `linear-gradient(${wipeDeg}deg, var(--${p}-sk-base) 42%, var(--${p}-sk-hi) 50%, var(--${p}-sk-base) 58%) 0 0 / 260% 100%`,
    slide: `linear-gradient(90deg, var(--${p}-sk-base) 40%, var(--${p}-sk-hi) 50%, var(--${p}-sk-base) 60%) 0 0 / 260% 100%`,
    glide: `linear-gradient(90deg, var(--${p}-sk-base) 30%, var(--${p}-sk-hi) 50%, var(--${p}-sk-base) 70%) 0 0 / 260% 100%`,
    flow: `linear-gradient(100deg, var(--${p}-sk-base) 25%, var(--${p}-sk-hi) 50%, var(--${p}-sk-base) 75%) 0 0 / 300% 100%`
  }[ch];
  const underlineOrigin = ch === 'glide' || ch === 'flow' ? '50% 100%' : '0 100%';
  const autoAlias = (k) => k === autoKind;

  return `/* ==========================================================================
   ${b.name} — ${p}-motion.css   (motion module of brand-system-forge)
   Character: ${ch} — ${M.signature}. Energy ${E}.
   Keyframes, reveal states, micro-interactions, loaders and transition layers.
   Durations and easings are the tokens from tokens.css (--duration-*, --ease-*);
   reduced motion zeroes them there and is handled again below (nothing stays hidden).
   Pair with SOURCE/JS/${p}-motion.js (adds .${p}-motion to <html> — hidden states apply only then).
   Generated by assets/modules/motion — regenerate rather than edit by hand.
   ========================================================================== */

/* ---------------------------------------------------------------- 0. Local tokens */
@property --${p}-p { syntax: '<number>'; inherits: false; initial-value: 1; }
:root {
  --${p}-motion-hover: var(--duration-fast);
  --${p}-motion-ui: var(--duration-base);
  --${p}-motion-panel: var(--duration-slow);
  --${p}-motion-section: var(--duration-slower);
  --${p}-motion-formation: var(--duration-formation);
  --${p}-ease-reveal: ${revealEase};
  --${p}-travel: ${travel}px;          /* entrance travel = 8 + 24 × energy */
  --${p}-stagger: ${stagger}ms;        /* child stagger  = 40 + 70 × energy */
  --${p}-wipe-angle: ${wipeDeg}deg;    /* gradient angle whose edge runs at the ${M.angle}° cut */
  --${p}-sweep-color: var(--color-brand-primary-hover);
}

/* ---------------------------------------------------------------- 1. Keyframes */
@keyframes ${p}-fade-in   { from { opacity: 0; } to { opacity: 1; } }
@keyframes ${p}-rise-in   { from { opacity: 0; transform: translate3d(0, var(--${p}-travel), 0); } to { opacity: 1; transform: none; } }
@keyframes ${p}-scale-in  { from { opacity: 0; transform: scale(.94); } to { opacity: 1; transform: none; } }
@keyframes ${p}-drift-in  { from { opacity: 0; transform: translate3d(0, calc(var(--${p}-travel) * 1.4), 0) scale(.985); } to { opacity: 1; transform: none; } }
@keyframes ${p}-wipe-in   { from { --${p}-p: 0; } to { --${p}-p: 1; } }
@keyframes ${p}-exit      { from { opacity: 1; transform: none; } to { opacity: 0; transform: translate3d(0, calc(var(--${p}-travel) * -.5), 0); } }
@keyframes ${p}-shimmer   { from { background-position: 130% 0; } to { background-position: -30% 0; } }
@keyframes ${p}-marquee   { from { transform: translateX(0); } to { transform: translateX(-50%); } }

/* ---------------------------------------------------------------- 2. Entrance utilities (play on load)
   .${p}-enter = the brand's default entrance (${autoKind}); the others are deliberate alternatives. */
.${p}-enter       { animation: ${p}-${autoKind === 'wipe' ? 'wipe' : autoKind}-in var(--${p}-motion-section) var(--${p}-ease-reveal) both; animation-delay: var(--${p}-delay, 0ms);${autoKind === 'wipe' ? ` -webkit-mask-image: ${wipeMask}; mask-image: ${wipeMask};` : ''} }
.${p}-enter-fade  { animation: ${p}-fade-in var(--${p}-motion-panel) var(--ease-standard) both; animation-delay: var(--${p}-delay, 0ms); }
.${p}-enter-rise  { animation: ${p}-rise-in var(--${p}-motion-section) var(--${p}-ease-reveal) both; animation-delay: var(--${p}-delay, 0ms); }
.${p}-enter-scale { animation: ${p}-scale-in var(--${p}-motion-section) var(--${p}-ease-reveal) both; animation-delay: var(--${p}-delay, 0ms); }
.${p}-enter-drift { animation: ${p}-drift-in calc(var(--${p}-motion-section) * 1.2) var(--ease-emphasis) both; animation-delay: var(--${p}-delay, 0ms); }
.${p}-enter-wipe  { animation: ${p}-wipe-in var(--${p}-motion-section) var(--${p}-ease-reveal) both; animation-delay: var(--${p}-delay, 0ms); -webkit-mask-image: ${wipeMask}; mask-image: ${wipeMask}; }
.${p}-stagger > * { animation: ${p}-${autoKind === 'wipe' ? 'rise' : autoKind}-in var(--${p}-motion-section) var(--${p}-ease-reveal) both; animation-delay: calc(var(--${p}-delay, 0ms) + var(--${p}-i, 0) * var(--${p}-stagger)); }
.${p}-exit        { animation: ${p}-exit var(--${p}-motion-ui) var(--ease-exit) both; pointer-events: none; }

/* ---------------------------------------------------------------- 3. Reveal on scroll (driven by ${b.G}.reveal)
   data-reveal = auto (→ ${autoKind}) | fade | rise | scale | drift | wipe | mask | count | logo
   data-reveal-stagger on a parent → its children enter in sequence. data-reveal-delay="120" (ms). */
.${p}-motion [data-reveal] { --${p}-delay: 0ms; }
${['fade', 'rise', 'scale', 'drift'].concat(autoKind !== 'wipe' ? ['auto'] : []).map(k => {
    const kk = k === 'auto' ? autoKind : k;
    const tr = kk === 'drift' ? `opacity calc(var(--${p}-motion-section) * 1.2) var(--ease-standard), transform calc(var(--${p}-motion-section) * 1.2) var(--ease-emphasis)`
      : `opacity var(--${p}-motion-section) var(--${p}-ease-reveal), transform var(--${p}-motion-section) var(--${p}-ease-reveal)`;
    const st = { fade: 'opacity: 0;', rise: `opacity: 0; transform: translate3d(0, var(--${p}-travel), 0);`, scale: 'opacity: 0; transform: scale(.94);', drift: `opacity: 0; transform: translate3d(0, calc(var(--${p}-travel) * 1.4), 0) scale(.985);` }[kk];
    return `${sel(k)} { transition: ${tr}; transition-delay: ${delay}; }\n${hid(k)} { ${st} }`;
  }).join('\n')}
${['wipe', 'mask'].concat(autoKind === 'wipe' ? ['auto'] : []).map(k => {
    const mask = k === 'mask' ? mediaMask : wipeMask;
    const extraTr = k !== 'mask' && ch === 'snap' ? `, transform var(--${p}-motion-section) var(--${p}-ease-reveal)` : '';
    const extraHid = k !== 'mask' && ch === 'snap' ? ` transform: translate3d(${(-Math.sin(M.angle * Math.PI / 180) * 10).toFixed(1)}px, ${(-Math.cos(M.angle * Math.PI / 180) * 10).toFixed(1)}px, 0);` : '';
    return `${sel(k)} { transition: --${p}-p var(--${p}-motion-section) var(--${p}-ease-reveal)${extraTr}; transition-delay: ${delay};\n  -webkit-mask-image: ${mask}; mask-image: ${mask}; }\n${hid(k)} { --${p}-p: 0;${extraHid} }`;
  }).join('\n')}
.${p}-motion [data-reveal="logo"]:not(.is-revealed) { visibility: hidden; }
/* once settled, masks are dropped so focus rings and shadows are never clipped */
.${p}-motion [data-reveal].is-settled, .${p}-motion [data-reveal].is-settled > * { -webkit-mask-image: none; mask-image: none; }

/* ---------------------------------------------------------------- 4. Hover & press (opt-in classes) */
.${p}-press { transition: transform var(--${p}-motion-hover) var(--ease-standard); }
.${p}-press:active { transform: ${pressMove}; }
.${p}-lift { transition: transform var(--${p}-motion-hover) var(--ease-standard), box-shadow var(--${p}-motion-hover) var(--ease-standard); }
.${p}-lift:hover, .${p}-lift:focus-within { transform: translate3d(0, -2px, 0); box-shadow: ${shadowHover}; }
.${p}-underline { text-decoration: none; background: linear-gradient(currentColor, currentColor) ${underlineOrigin} / 0 1px no-repeat; transition: background-size var(--${p}-motion-ui) var(--ease-standard); }
.${p}-underline:hover, .${p}-underline:focus-visible { background-size: 100% 1px; }
/* fill sweep (${ch}) — the label stays on top; colour = --${p}-sweep-color */
.${p}-sweep { position: relative; isolation: isolate; overflow: hidden; }
.${p}-sweep::before { content: ""; position: absolute; inset: 0; z-index: -1; pointer-events: none; background: var(--${p}-sweep-color);
  ${sweep} transition: transform var(--${p}-motion-ui) ${ch === 'flow' ? 'var(--ease-emphasis)' : 'var(--ease-standard)'}, opacity var(--${p}-motion-ui) var(--ease-standard); }
.${p}-sweep:hover::before, .${p}-sweep:focus-visible::before { ${sweepOn} }
.${p}-nudge .${p}-nudge__icon, .${p}-nudge > svg:last-child { display: inline-block; transition: transform var(--${p}-motion-hover) var(--ease-standard); }
.${p}-nudge:hover .${p}-nudge__icon, .${p}-nudge:focus-visible .${p}-nudge__icon, .${p}-nudge:hover > svg:last-child, .${p}-nudge:focus-visible > svg:last-child { transform: translateX(${ch === 'glide' ? 3 : 4}px); }
.${p}-zoom { overflow: hidden; }
.${p}-zoom :where(img, video, .${p}-zoom__media) { transition: transform var(--${p}-motion-panel) var(--ease-standard); }
.${p}-zoom:hover :where(img, video, .${p}-zoom__media), .${p}-zoom:focus-within :where(img, video, .${p}-zoom__media) { transform: scale(${zoom}); }

/* ---------------------------------------------------------------- 5. Loading */
.${p}-loader { display: inline-flex; align-items: center; justify-content: center; width: var(--${p}-loader-size, 48px); aspect-ratio: 1; vertical-align: middle; }
.${p}-loader__art { display: block; width: 100%; height: 100%; }
.${p}-loader__art svg, .${p}-lm-svg { display: block; width: 100%; height: 100%; overflow: visible; }
.${p}-skeleton { --${p}-sk-base: var(--color-surface-sunken); --${p}-sk-hi: var(--color-surface);
  background: ${shimmerBg}; animation: ${p}-shimmer ${ch === 'flow' ? 2200 : ch === 'glide' ? 1800 : 1500}ms ${ch === 'slide' ? 'steps(8)' : 'var(--ease-standard)'} infinite; color: transparent; border-radius: var(--radius-sm, 0); }
.${p}-count { font-variant-numeric: tabular-nums lining-nums; }

/* ---------------------------------------------------------------- 6. Marquee (${b.G}.marquee — adds a pause button) */
.${p}-marquee { position: relative; overflow: hidden; }
.${p}-marquee__track { display: flex; gap: var(--space-10, 40px); width: max-content; will-change: transform; }
.${p}-marquee__toggle { position: absolute; right: var(--space-2, 8px); top: 50%; transform: translateY(-50%); z-index: 2;
  font: var(--type-label-weight, 500) var(--type-label-size, .75rem)/1 var(--font-mono); letter-spacing: var(--type-label-letter-spacing, .06em); text-transform: uppercase;
  color: var(--color-text-primary); background: var(--color-surface); border: var(--border-hairline, 1px) solid var(--color-border); padding: var(--space-2, 8px) var(--space-3, 12px); border-radius: var(--radius-button, 0); cursor: pointer; }
.${p}-marquee.is-static .${p}-marquee__track { flex-wrap: wrap; width: auto; transform: none !important; row-gap: var(--space-3, 12px); padding-right: var(--space-24, 96px); }
.${p}-marquee.is-static .${p}-marquee__track > [aria-hidden="true"] { display: none; }

/* ---------------------------------------------------------------- 7. Page transition layers (${b.G}.transition) */
.${p}-wipe { position: fixed; inset: 0; z-index: var(--z-modal, 500); pointer-events: none; }
.${p}-wipe__layer { position: absolute; inset: 0; will-change: clip-path; }
.${p}-wipe--inline { position: absolute; z-index: 1; }

/* ---------------------------------------------------------------- 8. Reduced motion & still renders
   No movement, nothing hidden. Designed crops/masks (classes containing "${p}-mask" / "${p}-crop") are content, not motion: kept. */
@media (prefers-reduced-motion: reduce) {
  .${p}-motion [data-reveal]:not([class*="${p}-mask"]):not([class*="${p}-crop"]), .${p}-motion [data-reveal] > *:not([class*="${p}-mask"]):not([class*="${p}-crop"]) {
    opacity: 1 !important; transform: none !important; -webkit-mask-image: none !important; mask-image: none !important; visibility: visible !important; transition: none !important; }
  .${p}-motion [data-reveal][class*="${p}-mask"], .${p}-motion [data-reveal][class*="${p}-crop"] { opacity: 1 !important; transform: none !important; visibility: visible !important; transition: none !important; }
  .${p}-enter, .${p}-enter-fade, .${p}-enter-rise, .${p}-enter-scale, .${p}-enter-drift, .${p}-enter-wipe, .${p}-stagger > * { animation: none !important; -webkit-mask-image: none; mask-image: none; }
  .${p}-press:active, .${p}-lift:hover, .${p}-lift:focus-within, .${p}-zoom:hover :where(img, video, .${p}-zoom__media) { transform: none; }
  .${p}-sweep::before { transition: none; }
  .${p}-skeleton { animation: none; }
}
html[data-motion-still] .${p}-motion [data-reveal], html[data-motion-still] [data-reveal], html[data-motion-still] [data-reveal] > * { opacity: 1 !important; transform: none !important; -webkit-mask-image: none !important; mask-image: none !important; visibility: visible !important; transition: none !important; }
html[data-motion-still] .${p}-skeleton { animation: none; }
`;
};
