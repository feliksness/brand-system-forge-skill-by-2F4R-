function bez(s) { const m = /cubic-bezier\(([^)]+)\)/.exec(s || ''); return m ? m[1].split(',').map(Number) : null; }
function easeName(k, s) {
  const v = bez(s); if (!v) return 'linear';
  const over = v[1] > 1 || v[3] > 1, under = v[1] < 0 || v[3] < 0;
  if (over) return 'spring — overshoots ' + Math.round((Math.max(v[1], v[3]) - 1) * 100) + '% then settles';
  if (k === 'exit' || (v[0] > 0.4 && v[1] < 0.1)) return 'accelerate — leaves quickly, no lingering';
  if (v[0] < 0.3 && v[1] > 0.7) return 'strong decelerate — fast start, long soft landing';
  if (Math.abs(v[0] - v[2]) < 0.4 && v[1] < 0.2 && v[3] > 0.8) return 'in-out — symmetric, calm';
  return under ? 'anticipate' : 'decelerate';
}
